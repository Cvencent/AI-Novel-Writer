// 生成渲染进程 IPC 通道白名单（src/shared/ipc-channel-registry.ts）。
// 通道来源：ipc-channels.ts 的类型化键 + 主进程 ipcMain.handle/on 注册 + .send 事件。
// 新增通道后运行：node scripts/generate-ipc-channel-registry.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const isChannel = (s) => /^[a-z][a-z0-9-]*(:[a-z0-9-]+)+$/.test(s)

export function collectIpcChannels(root) {
  const channels = new Set()
  const ipcFile = fs.readFileSync(path.join(root, 'src/shared/ipc-channels.ts'), 'utf8')
  const keyRe = /'([^']+)'\s*:/g
  let m
  while ((m = keyRe.exec(ipcFile))) {
    if (isChannel(m[1])) channels.add(m[1])
  }
  /**
   * 另有一类通道只在**类型契约**里声明、由主进程按名注册（如 `startup-contract.ts` 的
   * `StartupChannels`：'startup:get-state' / 'startup:appearance-ack'）。它们不写成
   * `ipcMain.handle('...')` 字面量，上面的调用扫描同样抓不到——startup:get-state 一漏，
   * 渲染层连"主进程就绪"都问不到，整个工作台卡在启动页。
   * 这里把 shared 下的 `*contract*.ts` / `ipc-channels.ts` 里的通道键一并纳入。
   */
  const sharedDir = path.join(root, 'src/shared')
  for (const entry of fs.readdirSync(sharedDir, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.ts')) continue
    if (!/contract|ipc-channels/.test(entry.name) || /\.test\.ts$/.test(entry.name)) continue
    const text = fs.readFileSync(path.join(sharedDir, entry.name), 'utf8')
    const re = /'([a-z][a-z0-9-]*(?::[a-z0-9-]+)+)'\s*:/g
    let r
    while ((r = re.exec(text))) if (isChannel(r[1])) channels.add(r[1])
  }
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const fp = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (entry.name === '__tests__' || entry.name === 'node_modules') continue
        walk(fp)
      } else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts')) {
        const text = fs.readFileSync(fp, 'utf8')
        /**
         * ⚠️ 注册调用**不一定**写成 `ipcMain.handle(...)`。控制器常把 ipc 依赖注入进来，
         * 于是写成 `deps.ipc.handle('cloud-backup:backup', ...)` 或
         * `options.ipc.handle('startup:get-state', ...)`。原正则只认字面 `ipcMain.`，
         * 这两类全部漏掉 → 白名单缺通道 → preload 直接拒绝 → 渲染层卡在启动页
         * （issue #245 现场：startup:get-state 漏登记，整个工作台打不开）。
         * 改成匹配「<任意>.ipc.handle/on(」以及裸 `ipcMain.handle/on`。
         */
        const regRe = /(?:\bipcMain|\.ipc)\.(?:handle|handleOnce|on)\(\s*'([^']+)'/g
        /**
         * ⚠️ 还有一类完全不同的注册方式：控制器内部定义一个 `register(name, version, fn)`
         * 本地助手，通道名是它的**第一个参数**（如 generation-controller 的
         * `register('review-revision:prepare', 1, ...)`）。它不是 `ipcMain.` 也不是
         * `.ipc.`，上面两条都抓不到——漏掉的后果是 `review-revision:prepare` 不在白名单，
         * 作者一点 AI 审稿就报 `IPC channel not allowed`（issue #245 现场）。
         * 用「本文件里出现过 `register(` 定义」来判断这一类，避免误伤同名函数。
         */
        const helperRe = /\bregister\(\s*'([^']+)'/g
        const sendRe = /\.send\(\s*'([^']+)'/g
        let r
        while ((r = regRe.exec(text))) if (isChannel(r[1])) channels.add(r[1])
        while ((r = helperRe.exec(text))) if (isChannel(r[1])) channels.add(r[1])
        while ((r = sendRe.exec(text))) if (isChannel(r[1])) channels.add(r[1])
      }
    }
  }
  walk(path.join(root, 'electron'))
  return [...channels].sort()
}

export function renderRegistry(channels) {
  const lines = channels.map((c) => `  '${c}',`).join('\n')
  return `// AUTO-GENERATED by scripts/generate-ipc-channel-registry.mjs — do not edit by hand.
// 渲染进程允许使用的 IPC 通道白名单；preload 据此拒绝未知通道（纵深防御）。
// 新增通道后运行：node scripts/generate-ipc-channel-registry.mjs
export const IPC_CHANNEL_ALLOWLIST: ReadonlySet<string> = new Set([
${lines}
])
`
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const channels = collectIpcChannels(root)
  const target = path.join(root, 'src/shared/ipc-channel-registry.ts')
  fs.writeFileSync(target, renderRegistry(channels))
  console.log(`Wrote ${channels.length} channels to ${target}`)
}