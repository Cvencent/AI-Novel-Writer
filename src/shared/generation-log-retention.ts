/**
 * 生成日志的 Prompt 保留策略。
 *
 * 每次调用都记录完整 Prompt（日志页要能回看模型到底收到了什么），但只有最近
 * GENERATION_PROMPT_RETENTION 次调用保留完整的提示词：更早的记录会删掉
 * replayTask.messages，只留返回文本与用途、模型、token 这些摘要。
 *
 * 为什么必须有上限：大纲类调用的用户提示词会带上已确认大纲的上下文，单次可达 MB 级。
 * 全文永久保留会让作品的生成日志随章节数线性膨胀——实测一部 500 章作品能涨到几百 MB，
 * 打开作品与切页都会因此变慢。保留最近若干次覆盖了绝大多数「查最近一次为什么这样生成」
 * 的排查场景，又不会让库失控。
 *
 * 渲染层与主进程共用这一个常量，日志页据此告诉作者「更早的 Prompt 已按保留策略清理」。
 */
export const GENERATION_PROMPT_RETENTION = 200
